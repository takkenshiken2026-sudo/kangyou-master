def _build_terms(terms: Iterable[str], category: str) -> dict[str, dict[str, str]]:
    out: dict[str, dict[str, str]] = {}
    for term in terms:
        base = _default_payload(term, category)
        merged = _merge_payload(base, OVERRIDES.get(term, {}))
        out[term] = merged
    return out


