def _table(headers: list[str], rows: list[list[str]]) -> str:
    th = "".join(f"<th>{h}</th>" for h in headers)
    trs = []
    for row in rows:
        td = "".join(f"<td>{c}</td>" for c in row)
        trs.append(f"<tr>{td}</tr>")
    return (
        '<table class="seo-info-table">'
        "<thead>"
        f"<tr>{th}</tr>"
        "</thead>"
        "<tbody>"
        f"{''.join(trs)}"
        "</tbody>"
        "</table>"
    )


