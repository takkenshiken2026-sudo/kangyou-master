def pick_related(term: str, category: str, by_cat: dict[str, list[str]], n: int = 3) -> str:
    pool = [t for t in by_cat.get(category, []) if t != term]
    if len(pool) < n:
        for cat, terms in by_cat.items():
            if cat != category:
                pool.extend(t for t in terms if t != term)
    seen: set[str] = set()
    picked: list[str] = []
    for t in pool:
        if t in seen:
            continue
        seen.add(t)
        picked.append(t)
        if len(picked) >= n:
            break
    return ";".join(picked)


